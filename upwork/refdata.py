def _norm(text):
    return " ".join(str(text or "").lower().replace("&", "and").replace("-", " ").replace("_", " ").split())


LOCATION_BY_KEY = {}
for _uid, _name, _type in LOCATIONS:
    LOCATION_BY_KEY[_norm(_uid)] = (_name, _type)
    LOCATION_BY_KEY[_norm(_name)] = (_name, _type)
LOCATION_BY_KEY.update({"usa": ("United States", "country"), "us": ("United States", "country"),
                        "uk": ("United Kingdom", "country"), "gb": ("United Kingdom", "country"),
                        "uae": ("United Arab Emirates", "country"), "europe": ("Europe", "region")})

STATE_BY_KEY = {}
for _code, _name in US_STATES.items():
    STATE_BY_KEY[_norm(_code)] = _code
    STATE_BY_KEY[_norm(_name)] = _code

TIMEZONE_BY_KEY = {}
for _uid, _zone, _offset, _label in TIMEZONES:
    for _k in (_uid, _zone, _offset, _offset.replace("UTC", ""), _label):
        TIMEZONE_BY_KEY.setdefault(_norm(_k), (_zone, _offset))

CATEGORY_BY_KEY = {}
SUBCATEGORY_BY_KEY = {}
for _c in CATEGORIES:
    CATEGORY_BY_KEY[_c["id"]] = _c
    CATEGORY_BY_KEY[_norm(_c["name"])] = _c
    for _s in _c["subcategories"]:
        SUBCATEGORY_BY_KEY[_s["id"]] = _s
        SUBCATEGORY_BY_KEY.setdefault(_norm(_s["name"]), _s)


